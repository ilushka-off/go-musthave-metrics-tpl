// Command reset generates Reset methods for structs marked with a
// "generate:reset" comment.
//
// # Запуск
//
//	go run ./cmd/reset [root]
//
// root — корневая директория, с которой начинается рекурсивный обход (по
// умолчанию "."). Директории vendor, testdata и скрытые директории (с
// именем, начинающимся на ".") пропускаются, кроме случая, когда одна из
// них передана как сам root.
//
// # Как пометить структуру
//
// Поставьте комментарий "generate:reset" непосредственно над объявлением
// структуры:
//
//	// generate:reset
//	type Foo struct {
//		Name string
//	}
//
// # Что генерируется
//
// Для каждого файла, где найдена хотя бы одна такая структура, во всех
// пакетах, участвующих в обходе, создаётся (или перезаписывается) файл
// reset.gen.go в директории этого пакета, содержащий метод Reset() для
// каждой отмеченной структуры пакета (структуры из разных файлов одного
// пакета объединяются в одном reset.gen.go).
//
// # Правила сброса поля
//
//   - примитивы (int, string, bool, float64 и т.д.) сбрасываются в нулевое
//     значение своего типа;
//   - слайсы обрезаются до нулевой длины: s = s[:0], без обнуления самого
//     слайса;
//   - карты очищаются встроенной функцией clear;
//   - указатели на примитивы: если указатель не nil, обнуляется значение,
//     на которое он указывает (*p = 0), сам указатель не трогается;
//   - любое другое поле (вложенная структура по значению или по указателю,
//     тип из другого пакета, интерфейс) проверяется на реализацию
//     интерфейса interface{ Reset() } через приведение типа в рантайме, и
//     если структура реализует его — вызывается Reset(); для указателя
//     проверка выполняется только если он не nil. Это не требует полной
//     информации о типах (go/types) — достаточно go/ast, так как проверка
//     "умеет ли значение Reset()" происходит во время выполнения
//     сгенерированного кода, а не во время генерации;
//   - поля фиксированного размера (массивы) и поля, для которых не удалось
//     определить синтаксическую категорию, оставляются без изменений.
