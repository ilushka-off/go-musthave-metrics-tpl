// Command staticlint is a multichecker that combines several groups of
// static analyzers for this project:
//
//   - a selection of standard analyzers from
//     golang.org/x/tools/go/analysis/passes;
//   - all SA analyzers from honnef.co/go/tools/staticcheck (staticcheck.io);
//   - one analyzer from another staticcheck.io class,
//     honnef.co/go/tools/stylecheck (ST1005);
//   - two third-party public analyzers, errcheck and bodyclose;
//   - a custom analyzer, noosexit, that forbids a direct call to os.Exit
//     inside func main of package main.
//
// # Запуск
//
// Собрать бинарник и запустить его на нужном наборе пакетов (аргументы —
// как в go vet):
//
//	go build -o staticlint ./cmd/staticlint
//	./staticlint ./...
//
// Список всех включённых анализаторов и их собственных флагов можно
// получить через:
//
//	./staticlint -help
//
// Отдельный анализатор можно включить/выключить явно, например:
//
//	./staticlint -SA1000=false ./...
//
// # Анализаторы golang.org/x/tools/go/analysis/passes
//
//   - asmdecl — проверяет соответствие объявлений в файлах ассемблера
//     Go-декларациям функций.
//   - assign — находит бесполезные самоприсваивания вида x = x.
//   - atomic — находит неправильные вызовы функций пакета sync/atomic.
//   - bools — находит подозрительные булевы выражения (x || x, x && !x).
//   - buildtag — проверяет корректность build-тегов (// +build, //go:build).
//   - cgocall — находит нарушения правил передачи Go-указателей через cgo.
//   - composite — требует явных имён полей в составных литералах из
//     других пакетов, чтобы литерал не «рассыпался» при изменении порядка полей.
//   - copylock — находит копирование значений, содержащих sync.Mutex и
//     подобные типы, которые нельзя копировать после первого использования.
//   - errorsas — проверяет, что второй аргумент errors.As — это указатель,
//     реализующий интерфейс error.
//   - httpresponse — находит некорректные проверки результата
//     http.Get/Head/Post (например, использование res после ошибки).
//   - ifaceassert — находит невозможные проверки типа для интерфейсов,
//     которые не могут выполниться ни при каких обстоятельствах.
//   - loopclosure — находит захват переменной цикла в замыкании,
//     запускаемом в отдельной горутине или defer.
//   - lostcancel — находит утерянные context.CancelFunc, которые не
//     вызываются ни разу.
//   - nilfunc — находит бессмысленные сравнения функций с nil там, где
//     значение всегда не-nil.
//   - nilness — находит обращения по указателю, который заведомо равен
//     nil, и другие подобные проблемы.
//   - printf — проверяет соответствие форматных строк аргументам
//     Printf-подобных функций.
//   - shadow — находит затенение переменных внутренними объявлениями с
//     тем же именем.
//   - shift — находит битовые сдвиги, превышающие ширину типа операнда.
//   - sortslice — находит некорректные вызовы sort.Slice (не-слайс
//     аргумент, функция сравнения с неверной сигнатурой).
//   - stdmethods — проверяет сигнатуры хорошо известных методов
//     (String, Error, Scan и т.п.) на соответствие стандартным интерфейсам.
//   - stringintconv — находит подозрительные конверсии string(int),
//     которые дают код UTF-8 руны, а не десятичную строку.
//   - structtag — проверяет корректность синтаксиса тегов структур
//     (json, xml и т.д.).
//   - testinggoroutine — находит вызовы t.Fatal/t.FailNow из горутины,
//     отличной от той, что выполняет тест.
//   - tests — проверяет сигнатуры функций Test/Benchmark/Example на
//     соответствие требованиям пакета testing.
//   - unmarshal — находит передачу не-указателя или nil-указателя в
//     функции json.Unmarshal и подобные.
//   - unreachable — находит недостижимый код после return/panic/бесконечного цикла.
//   - unsafeptr — находит недопустимые конверсии uintptr в unsafe.Pointer.
//   - unusedresult — находит игнорирование результата вызова функций,
//     которые обязаны использоваться (например, fmt.Sprintf, errors.New).
//   - unusedwrite — находит записи в поля структуры или элементы массива,
//     значение которых затем никогда не читается.
//
// # Анализаторы staticcheck.io класса SA
//
// Включены все анализаторы из honnef.co/go/tools/staticcheck (SA1000 —
// SA9xxx). Они находят реальные баги: неправильное использование
// стандартной библиотеки, ошибки работы с контекстом и конкурентностью,
// утечки ресурсов, неверные форматные строки и т.п. Полный список с
// описанием каждой проверки: https://staticcheck.dev/docs/checks/#SA
//
// # Анализатор другого класса staticcheck.io
//
//   - ST1005 (honnef.co/go/tools/stylecheck) — сообщения об ошибках не
//     должны начинаться с заглавной буквы и не должны заканчиваться
//     знаком пунктуации, в соответствии с конвенцией errors.New/fmt.Errorf
//     в стандартной библиотеке.
//
// # Публичные анализаторы
//
//   - errcheck (github.com/kisielk/errcheck/errcheck) — находит места,
//     где возвращаемое значение ошибки игнорируется без явного
//     присваивания в "_".
//   - bodyclose (github.com/timakin/bodyclose/passes/bodyclose) — находит
//     HTTP response body (http.Response.Body), для которых не был вызван
//     Close, что приводит к утечке соединений.
//
// # Собственный анализатор
//
//   - noosexit (cmd/staticlint/noosexit) — запрещает прямой вызов os.Exit
//     внутри функции main пакета main. Прямой os.Exit в main обходит
//     отложенные вызовы defer и усложняет тестирование; логику,
//     завершающую процесс с ненулевым кодом, следует выносить в отдельную
//     функцию и вызывать os.Exit на основе её результата за пределами main,
//     либо не завершать процесс из main вовсе.
